#!/usr/bin/env node
"use strict";

/**
 * Refresh items-registry.js from Prismarine Java 26.1 item data.
 *   node generate_items.js
 */
const fs = require("fs");
const path = require("path");
const https = require("https");

const URL = "https://raw.githubusercontent.com/PrismarineJS/minecraft-data/master/data/pc/26.1/items.json";

function fetchJson(url) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode !== 200) {
        reject(new Error(`HTTP ${res.statusCode}`));
        return;
      }
      let body = "";
      res.on("data", (c) => { body += c; });
      res.on("end", () => {
        try { resolve(JSON.parse(body)); }
        catch (e) { reject(e); }
      });
    }).on("error", reject);
  });
}

async function main() {
  const raw = await fetchJson(URL);
  const items = raw
    .filter((it) => it.name && it.name !== "air")
    .map((it) => ({
      id: it.name,
      name: it.displayName || it.name.replace(/_/g, " "),
    }))
    .sort((a, b) => a.id.localeCompare(b.id));

  const out = path.join(__dirname, "items-registry.js");
  const payload = JSON.stringify(items, null, 2);
  const src = `/** Minecraft item registry (Java 26.1 Prismarine data; close to 26.2). Regenerated by generate_items.js */\n(function (global) {\n  const MC_ITEMS = ${payload};\n  const byId = Object.fromEntries(MC_ITEMS.map((i) => [i.id, i]));\n  function searchItems(q, limit) {\n    const n = limit == null ? 40 : limit;\n    const s = String(q || "").trim().toLowerCase();\n    if (!s) return MC_ITEMS.slice(0, n);\n    const out = [];\n    for (const it of MC_ITEMS) {\n      if (it.id.includes(s) || it.name.toLowerCase().includes(s)) {\n        out.push(it);\n        if (out.length >= n) break;\n      }\n    }\n    return out;\n  }\n  const api = { MC_ITEMS, byId, searchItems };\n  if (typeof module !== "undefined" && module.exports) module.exports = api;\n  global.ItemRegistry = api;\n})(typeof window !== "undefined" ? window : globalThis);\n`;
  fs.writeFileSync(out, src);
  console.log("wrote", out, items.length, "items");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
